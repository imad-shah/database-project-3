CREATE EXTENSION IF NOT EXISTS lo;

CREATE TABLE IF NOT EXISTS agents (
    agent_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name      TEXT NOT NULL,
    last_name       TEXT NOT NULL,
    phone           TEXT,
    email           TEXT,
    license_number  TEXT NOT NULL,
    hire_date       DATE NOT NULL,
    CONSTRAINT agents_email_unique UNIQUE (email),
    CONSTRAINT agents_license_unique UNIQUE (license_number)
);

CREATE TABLE IF NOT EXISTS buyers (
    buyer_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name      TEXT NOT NULL,
    last_name       TEXT NOT NULL,
    phone           TEXT,
    email           TEXT,
    max_budget      NUMERIC(12, 2),
    min_bedrooms    INTEGER,
    preferred_city  TEXT,
    CONSTRAINT buyers_budget_positive CHECK (max_budget > 0),
    CONSTRAINT buyers_bedrooms_valid CHECK (min_bedrooms >= 0)
);

CREATE TABLE IF NOT EXISTS sellers (
    seller_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  TEXT NOT NULL,
    last_name   TEXT NOT NULL,
    phone       TEXT,
    email       TEXT
);

CREATE TABLE IF NOT EXISTS properties (
    property_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    street            TEXT NOT NULL,
    city              TEXT NOT NULL,
    state             TEXT NOT NULL,
    zip_code          TEXT NOT NULL,
    school_district   TEXT NOT NULL,
    bedrooms          INTEGER NOT NULL,
    bathrooms         NUMERIC(3, 1) NOT NULL,
    square_feet       INTEGER NOT NULL,
    year_built        INTEGER,
    has_pool          BOOLEAN NOT NULL,
    image             LO,
    CONSTRAINT properties_address_unique UNIQUE (street, city, state, zip_code),
    CONSTRAINT properties_state_format CHECK (state ~ '^[A-Z]{2}$'),
    CONSTRAINT properties_zip_format CHECK (zip_code ~ '^[0-9]{5}(-[0-9]{4})?$'),
    CONSTRAINT properties_bedrooms_valid CHECK (bedrooms >= 0),
    CONSTRAINT properties_bathrooms_valid CHECK (bathrooms >= 0),
    CONSTRAINT properties_square_feet_positive CHECK (square_feet > 0),
    CONSTRAINT properties_year_built_valid CHECK (year_built BETWEEN 1600 AND 2100)
);

CREATE TABLE IF NOT EXISTS listings (
    listing_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id       INTEGER NOT NULL,
    seller_id         INTEGER NOT NULL,
    listing_agent_id  INTEGER NOT NULL,
    asking_price      NUMERIC(12, 2) NOT NULL,
    listing_date      DATE NOT NULL,
    CONSTRAINT listings_price_positive CHECK (asking_price > 0),
    CONSTRAINT listings_property_fk FOREIGN KEY (property_id) REFERENCES properties (property_id),
    CONSTRAINT listings_seller_fk FOREIGN KEY (seller_id) REFERENCES sellers (seller_id),
    CONSTRAINT listings_listing_agent_fk FOREIGN KEY (listing_agent_id) REFERENCES agents (agent_id)
);

CREATE TABLE IF NOT EXISTS sales (
    sale_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id        INTEGER NOT NULL,
    buyer_id          INTEGER NOT NULL,
    selling_agent_id  INTEGER NOT NULL,
    buyers_agent_id   INTEGER,
    sale_price        NUMERIC(12, 2) NOT NULL,
    sale_date         DATE NOT NULL,
    CONSTRAINT sales_listing_unique UNIQUE (listing_id),
    CONSTRAINT sales_price_positive CHECK (sale_price > 0),
    CONSTRAINT sales_listing_fk FOREIGN KEY (listing_id) REFERENCES listings (listing_id),
    CONSTRAINT sales_buyer_fk FOREIGN KEY (buyer_id) REFERENCES buyers (buyer_id),
    CONSTRAINT sales_selling_agent_fk FOREIGN KEY (selling_agent_id) REFERENCES agents (agent_id),
    CONSTRAINT sales_buyers_agent_fk FOREIGN KEY (buyers_agent_id) REFERENCES agents (agent_id)
);

CREATE INDEX IF NOT EXISTS properties_city_idx ON properties (lower(city));
CREATE INDEX IF NOT EXISTS properties_district_bedrooms_idx ON properties (lower(school_district), bedrooms);
CREATE INDEX IF NOT EXISTS listings_property_idx ON listings (property_id);
CREATE INDEX IF NOT EXISTS listings_seller_idx ON listings (seller_id);
CREATE INDEX IF NOT EXISTS listings_listing_agent_idx ON listings (listing_agent_id);
CREATE INDEX IF NOT EXISTS sales_date_idx ON sales (sale_date);
CREATE INDEX IF NOT EXISTS sales_selling_agent_date_idx ON sales (selling_agent_id, sale_date);
CREATE INDEX IF NOT EXISTS sales_buyers_agent_idx ON sales (buyers_agent_id);
CREATE INDEX IF NOT EXISTS sales_buyer_idx ON sales (buyer_id);

CREATE OR REPLACE TRIGGER properties_image_cleanup
    BEFORE UPDATE OR DELETE ON properties
    FOR EACH ROW EXECUTE FUNCTION lo_manage(image);

CREATE OR REPLACE FUNCTION enforce_sale_after_listing() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.sale_date < (SELECT listing_date FROM listings WHERE listing_id = NEW.listing_id) THEN
        RAISE EXCEPTION 'sale date precedes listing date'
            USING ERRCODE = 'check_violation', CONSTRAINT = 'sale_after_listing';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER sales_after_listing
    BEFORE INSERT OR UPDATE ON sales
    FOR EACH ROW EXECUTE FUNCTION enforce_sale_after_listing();

CREATE OR REPLACE FUNCTION enforce_listing_before_sale() RETURNS TRIGGER AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM sales
        WHERE listing_id = NEW.listing_id AND sale_date < NEW.listing_date
    ) THEN
        RAISE EXCEPTION 'listing date follows sale date'
            USING ERRCODE = 'check_violation', CONSTRAINT = 'sale_after_listing';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER listings_listing_before_sale
    BEFORE UPDATE OF listing_date ON listings
    FOR EACH ROW EXECUTE FUNCTION enforce_listing_before_sale();

CREATE OR REPLACE FUNCTION has_multiple_active_listings(target INTEGER) RETURNS BOOLEAN AS $$
BEGIN
    PERFORM 1 FROM properties WHERE property_id = target FOR NO KEY UPDATE;
    RETURN (
        SELECT count(*) > 1 FROM listings l
        WHERE l.property_id = target
          AND NOT EXISTS (SELECT 1 FROM sales s WHERE s.listing_id = l.listing_id)
    );
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION enforce_one_active_listing() RETURNS TRIGGER AS $$
BEGIN
    IF has_multiple_active_listings(NEW.property_id) THEN
        RAISE EXCEPTION 'property already has an active listing'
            USING ERRCODE = 'check_violation', CONSTRAINT = 'listings_one_active';
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER listings_one_active
    AFTER INSERT ON listings
    FOR EACH ROW EXECUTE FUNCTION enforce_one_active_listing();

CREATE OR REPLACE FUNCTION enforce_property_fixed() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.property_id <> OLD.property_id THEN
        RAISE EXCEPTION 'listing property cannot change'
            USING ERRCODE = 'check_violation', CONSTRAINT = 'listings_property_fixed';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER listings_property_fixed
    BEFORE UPDATE OF property_id ON listings
    FOR EACH ROW EXECUTE FUNCTION enforce_property_fixed();

CREATE OR REPLACE FUNCTION enforce_after_prior_sale() RETURNS TRIGGER AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM listings l
        JOIN sales s ON s.listing_id = l.listing_id
        WHERE l.property_id = NEW.property_id
          AND l.listing_id <> NEW.listing_id
          AND s.sale_date > NEW.listing_date
          AND l.listing_date < COALESCE(
              (SELECT sale_date FROM sales WHERE listing_id = NEW.listing_id),
              'infinity'
          )
    ) THEN
        RAISE EXCEPTION 'listing overlaps an earlier sale of the property'
            USING ERRCODE = 'check_violation', CONSTRAINT = 'listings_after_prior_sale';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER listings_after_prior_sale
    BEFORE INSERT OR UPDATE OF listing_date, property_id ON listings
    FOR EACH ROW EXECUTE FUNCTION enforce_after_prior_sale();

CREATE OR REPLACE FUNCTION enforce_sale_kept_after_relisting() RETURNS TRIGGER AS $$
BEGIN
    IF has_multiple_active_listings(
        (SELECT property_id FROM listings WHERE listing_id = OLD.listing_id)
    ) THEN
        RAISE EXCEPTION 'property was relisted after this sale'
            USING ERRCODE = 'check_violation', CONSTRAINT = 'sales_relisted_property';
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER sales_relisted_property
    AFTER DELETE OR UPDATE OF listing_id ON sales
    FOR EACH ROW EXECUTE FUNCTION enforce_sale_kept_after_relisting();

DROP VIEW IF EXISTS property_overview;
DROP VIEW IF EXISTS property_listings;

CREATE VIEW property_listings AS
SELECT l.listing_id,
       p.property_id,
       p.street,
       p.city,
       p.state,
       p.zip_code,
       p.school_district,
       p.bedrooms,
       p.bathrooms,
       p.square_feet,
       p.year_built,
       p.has_pool,
       l.seller_id,
       l.listing_agent_id,
       l.asking_price,
       l.listing_date,
       CASE WHEN s.sale_id IS NULL THEN 'Available' ELSE 'Sold' END AS status,
       p.image IS NOT NULL AS has_photo,
       COALESCE(s.sale_price, l.asking_price) AS price
FROM listings l
JOIN properties p ON p.property_id = l.property_id
LEFT JOIN sales s ON s.listing_id = l.listing_id;

CREATE VIEW property_overview AS
SELECT p.property_id,
       p.street,
       p.city,
       p.state,
       p.zip_code,
       p.school_district,
       p.bedrooms,
       p.bathrooms,
       p.square_feet,
       p.year_built,
       p.has_pool,
       CASE
           WHEN bool_or(l.status = 'Available') THEN 'Available'
           WHEN bool_or(l.status = 'Sold') THEN 'Sold'
           ELSE 'Not Listed'
       END AS status,
       p.image IS NOT NULL AS has_photo
FROM properties p
LEFT JOIN property_listings l ON l.property_id = p.property_id
GROUP BY p.property_id;
